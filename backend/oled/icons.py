def draw_icon(draw, name: str, x: int, y: int, size: int = 8):
    """Zeichne ein Pixel-Icon auf ein Pillow ImageDraw."""
    icons = ICONS_8x8 if size == 8 else ICONS_16x16
    icon = icons.get(name)
    if not icon:
        return
    for row_idx, row in enumerate(icon):
        for col_idx, pixel in enumerate(row):
            if pixel == "1":
                draw.point((x + col_idx, y + row_idx), fill=1)


def condition_to_icon(condition: str) -> str:
    """Wetter-Condition-String → Icon-Name."""
    c = condition.lower() if condition else ""
    if "gewitter" in c or "thunder" in c:
        return "thunder"
    if "schnee" in c or "snow" in c:
        return "snow"
    if "stark" in c and "regen" in c or "heavy" in c:
        return "heavy_rain"
    if "regen" in c or "rain" in c or "shower" in c or "drizzle" in c:
        return "rain"
    if "nebel" in c or "fog" in c or "mist" in c:
        return "fog"
    if "wind" in c:
        return "wind"
    if "bewoelkt" in c or "cloudy" in c or "overcast" in c:
        return "cloud"
    if "teilweise" in c or "partly" in c or "wolkig" in c:
        return "sun_cloud"
    if "nacht" in c or "night" in c or "clear" in c and "night" in c:
        return "moon"
    if "klar" in c or "sonnig" in c or "clear" in c or "sunny" in c:
        return "sun"
    return "sun_cloud"
